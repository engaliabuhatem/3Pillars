// Builds the 50–950 brand scales in OKLCH and writes src/styles/palette.css.
// The CI hex sits at 600 and the contrast-verified tints from the brand brief
// are pinned at their steps; every other step is interpolated in OKLCH
// lightness between those anchors so the pinned values never drift.
// Run: node scripts/generate-palette.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { hexToOklch, oklchToHex } from '../src/lib/color.mjs';

const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];

const BRAND = {
  navy: { 600: '#191747', ends: { 50: 0.975, 950: 0.13 } },
  blue: { 600: '#0B5EAC', 300: '#6D9ECD', 200: '#9DBFDE', ends: { 50: 0.975, 950: 0.2 } },
  green: { 600: '#136131', 300: '#71A083', 200: '#A1C0AD', ends: { 50: 0.975, 950: 0.18 } },
  grey: { 600: '#5C5E60', 300: '#9D9EA0', ends: { 50: 0.98, 950: 0.18 } },
};

function ramp(spec) {
  const base = hexToOklch(spec[600]);
  const anchors = new Map([[50, spec.ends[50]], [950, spec.ends[950]]]);
  for (const step of STEPS) if (spec[step]) anchors.set(step, hexToOklch(spec[step]).l);
  const known = [...anchors.keys()].sort((a, b) => a - b);

  return Object.fromEntries(
    STEPS.map((step) => {
      if (spec[step]) return [step, spec[step].toUpperCase()];
      const hi = known.find((k) => k >= step);
      const lo = [...known].reverse().find((k) => k <= step);
      const t = hi === lo ? 0 : (step - lo) / (hi - lo);
      const l = anchors.get(lo) + (anchors.get(hi) - anchors.get(lo)) * t;
      // Chroma peaks around the CI step and tapers toward paper and ink, which
      // keeps 50/100 usable as tinted backgrounds rather than pastel candy.
      const distance = Math.abs(l - base.l) / Math.max(base.l, 1 - base.l);
      const c = base.c * Math.max(0.12, 1 - distance * 0.9);
      return [step, oklchToHex({ l, c, h: base.h })];
    }),
  );
}

const lines = ['/* Generated by scripts/generate-palette.mjs — do not edit by hand. */', '@theme {'];
for (const [name, spec] of Object.entries(BRAND)) {
  const scale = ramp(spec);
  lines.push(`  --color-${name}: ${scale[600]};`);
  for (const step of STEPS) lines.push(`  --color-${name}-${step}: ${scale[step]};`);
}
lines.push('}', '');

const out = fileURLToPath(new URL('../src/styles/palette.css', import.meta.url));
writeFileSync(out, lines.join('\n'));
console.log(`wrote ${out}`);
